import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import { Workbench } from '../server/workbench';
import { validateRepository } from '../server/repository-configuration';
import { defaultRoles } from '../server/roles';
import { resolveAssignment } from '../server/runtime/model-policy';
import { RustMailClient, Messaging } from '../server/runtime/messaging';

const config = JSON.parse(readFileSync(process.argv[2], 'utf8'));
execFileSync('git', ['-C', config.root, 'init', '-b', 'main'], { stdio: 'ignore' });
execFileSync('git', ['-C', config.root, '-c', 'user.name=Fixture', '-c', 'user.email=fixture@example.invalid', 'commit', '--allow-empty', '-m', 'fixture'], { stdio: 'ignore' });
let store = new Workbench(join(config.root, 'workflow.sqlite'));
try {
  const repository = store.saveRepository(await validateRepository({ name: 'Fixture', path: config.root, targetBranch: 'main' }, path => store.isOwnedRepositoryWorktree(path)));
  const task = store.createTask({ title: 'External messages', description: '', repositoryId: repository.id });
  store.refine(task.id, { revision: 1, sourceRevision: 1, brief: 'Exchange messages', criteria: ['Durable, observable delivery'] });
  const run = store.queue(task.id, { revision: 2 });
  const role = { ...defaultRoles[1], model: 'fixture/model', effort: 'low' as const };
  const model = resolveAssignment(role, [{ provider: 'fixture', id: 'model', api: 'openai-responses', inputs: ['text'], efforts: ['low'], tools: true }], {}, {});
  const c = store.admitAssignment(run.id, { name: 'Coordinator', role, model, coordinator: true, input: 'Coordinate.' });
  const s = store.admitAssignment(run.id, { name: 'Specialist', role, model, coordinator: false, input: 'Investigate.' });
  const mail = new RustMailClient(config.url, config.token);
  let messages = new Messaging(store, mail, config.project, 86400);
  await messages.register(run.id);
  const first = await messages.send(c.attempt.id, 'call-1', { to: 'Specialist', body: 'Check zero.' });
  assert.ok(first.transportId);
  const second = await messages.send(c.attempt.id, 'call-1', { to: 'Specialist', body: 'Check zero.' });
  assert.equal(second.transportId, first.transportId);
  const before = await mail.call('get_message_delivery_receipt', { project_key: config.project, message_id: first.transportId });
  const events = await messages.observe(run.id);
  assert.ok(events.some(event => event.message_id === first.transportId));
  assert.deepEqual(await mail.call('get_message_delivery_receipt', { project_key: config.project, message_id: first.transportId }), before);
  store.close(); store = new Workbench(join(config.root, 'workflow.sqlite'));
  messages = new Messaging(store, new RustMailClient(config.url, config.token), config.project, 86400);
  assert.equal((await messages.send(c.attempt.id, 'call-1', { to: 'Specialist', body: 'Check zero.' })).transportId, first.transportId);
  assert.deepEqual(await messages.observe(run.id), []);
  await messages.accept(first.id);
  const receipt = await mail.call('get_message_delivery_receipt', { project_key: config.project, message_id: first.transportId });
  assert.equal(receipt.recipients[0].acknowledged, true);
  const reply = await messages.send(s.attempt.id, 'call-2', { to: 'Coordinator', body: 'Zero confirmed.', replyTo: first.id });
  assert.equal(reply.replyTo, first.id);
  const inbox = await mail.call('fetch_inbox', { project_key: config.project, agent_name: store.runtime(run.id).assignments[1].mailboxName, include_bodies: true, mark_read: false, limit: 100 });
  assert.equal(inbox.filter((message: any) => message.subject === first.id).length, 1);
  const windows = ['before-persistence', 'after-persistence', 'before-ack', 'after-ack', 'after-processing'];
  for (const window of windows) {
    const message = await messages.send(c.attempt.id, `window-${window}`, { to: 'Specialist', body: `Crash at ${window}` });
    store.close();
    const child = spawnSync(process.execPath, ['--import', 'tsx', 'scripts/mail-window-worker.ts', process.argv[2], message.id, s.attempt.id, window], { encoding: 'utf8', timeout: 15000 });
    assert.equal(child.signal, 'SIGKILL', child.stdout + child.stderr);
    store = new Workbench(join(config.root, 'workflow.sqlite'));
    messages = new Messaging(store, new RustMailClient(config.url, config.token), config.project, 86400);
    const saved = store.getPeerMessage(message.id);
    assert.equal(saved.disposition, window === 'before-persistence' ? 'stored' : window === 'after-processing' ? 'received' : 'accepted');
    const transport = await mail.call('get_message_delivery_receipt', { project_key: config.project, message_id: message.transportId });
    assert.equal(transport.recipients[0].acknowledged, ['after-ack', 'after-processing'].includes(window));
    await messages.accept(message.id); store.recordDispatch(message.id, true);
    const effect = await messages.send(s.attempt.id, `effect-${message.id}`, { to: 'Coordinator', body: `Effect for ${message.id}`, replyTo: message.id });
    assert.equal((await messages.send(s.attempt.id, `effect-${message.id}`, { to: 'Coordinator', body: `Effect for ${message.id}`, replyTo: message.id })).id, effect.id);
    const effects = await mail.call('fetch_inbox', { project_key: config.project, agent_name: store.runtime(run.id).assignments[0].mailboxName, include_bodies: true, mark_read: false, limit: 100 });
    assert.equal(effects.filter((entry: any) => entry.subject === effect.id).length, 1);
    assert.equal(store.runtime(run.id).messages.filter(entry => entry.toolCallId === `effect-${message.id}`).length, 1);
  }
  await assert.rejects(messages.send(c.attempt.id, 'lost-call', { to: 'Specialist', body: 'LOSE_REPLY' }));
  const lost = store.runtime(run.id).messages.find(message => message.toolCallId === 'lost-call')!;
  assert.equal(lost.transportId, undefined);
  const expired = new Messaging(store, mail, config.project, 1, () => Date.now() + 5000);
  store.recordOwnership(c.attempt.id, true);
  const reconciled = await expired.reconcile(lost.id);
  assert.ok(reconciled.transportId);
  const absent = store.prepareMessage(s.attempt.id, 'absent-call', { to: 'Coordinator', body: 'Never sent' });
  await assert.rejects(expired.reconcile(absent.id), /uncertain.*Do not resend/);
  const after = await mail.call('fetch_inbox', { project_key: config.project, agent_name: store.runtime(run.id).assignments[1].mailboxName, include_bodies: true, mark_read: false, limit: 100 });
  assert.equal(after.filter((message: any) => message.body_md === 'LOSE_REPLY').length, 1);
  assert.equal(after.filter((message: any) => message.body_md === 'Never sent').length, 0);
  const control = async (path: string) => { const response = await fetch(config.controlUrl + path, { method: 'POST' }); assert.ok(response.ok); };
  await control('/offline');
  await assert.rejects(messages.send(s.attempt.id, 'outage-call', { to: 'Coordinator', body: 'Retain through downtime' }), /503/);
  const pending = store.runtime(run.id).messages.find(message => message.toolCallId === 'outage-call')!;
  assert.equal(pending.disposition, 'pending'); assert.equal(pending.transportId, undefined);
  await control('/online');
  const recovered = await messages.reconcile(pending.id); assert.ok(recovered.transportId);
  await control('/restart');
  store.close(); store = new Workbench(join(config.root, 'workflow.sqlite'));
  messages = new Messaging(store, new RustMailClient(config.url, config.token), config.project, 86400);
  assert.equal((await messages.send(s.attempt.id, 'outage-call', { to: 'Coordinator', body: 'Retain through downtime' })).transportId, recovered.transportId);
  await messages.accept(recovered.id);
  const recoveredInbox = await mail.call('fetch_inbox', { project_key: config.project, agent_name: store.runtime(run.id).assignments[0].mailboxName, include_bodies: true, mark_read: false, limit: 100 });
  assert.equal(recoveredInbox.filter((message: any) => message.subject === recovered.id).length, 1);
  console.log(JSON.stringify({ passed: true, runId: run.id, messageIds: [first.transportId, reply.transportId, recovered.transportId], checks: ['five killed-process receive boundaries', 'one durable/external reply effect per replayed receive', 'keyed send', 'reopen deduplication', 'passive durable cursor', 'durable input before acknowledgement', 'causal reply', 'lost-response reconciliation after key expiry', 'uncertain expired send blocked', 'service downtime preserves pending intent', 'two service restarts retain one logical effect'] }));
} finally { store.close(); }
