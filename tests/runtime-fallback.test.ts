import assert from 'node:assert/strict';
import { test } from 'node:test';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { Workbench } from '../server/workbench';
import { seedRepository, saveRepositoryFixture } from './fixtures/repository';
import { defaultRoles } from '../server/roles';
import { resolveAssignment, resolveRuntimeFallback } from '../server/runtime/model-policy';
import { attemptModel } from '../server/runtime/types';
import { readRunHistory } from '../server/run-history';

test('RTE-09: a fallback records immutable attempt identity, cause, lineage and usage across reopen', t => {
  const root = mkdtempSync(join(tmpdir(), 'crewroom-fallback-')); seedRepository(root);
  let store = new Workbench(join(root, 'db')); t.after(() => { store.close(); rmSync(root, { recursive: true, force: true }); });
  const repo = saveRepositoryFixture(store, { name: 'Fixture', path: root, targetBranch: 'main' });
  const task = store.createTask({ title: 'Retain failure', description: '', repositoryId: repo.id });
  store.refine(task.id, { revision: 1, sourceRevision: 1, brief: 'Keep the exact model per attempt', criteria: ['History and usage stay truthful'] });
  const run = store.queue(task.id, { revision: 2 });
  const role = { ...defaultRoles[0], model: 'fixture/first', effort: 'low' as const };
  const catalog = ['first','second'].map(id => ({ provider: 'fixture', id, api: 'openai-responses', inputs: ['text'], efforts: ['low'], tools: true }));
  const model = resolveAssignment(role, catalog, {}, {});
  const next = resolveRuntimeFallback(role, model, catalog, { fallbacks: { 'fixture/first': [{ model: 'fixture/second', effort: 'low' }] } }, { tools: true }, [])!;
  const original = store.admitAssignment(run.id, { name: 'Coordinator', role, model, coordinator: true, input: 'Retain this instruction.' });
  store.claimAttempt(original.attempt.id);
  store.recordAttemptIdentity(original.attempt.id, { hostPid: 10, ompPid: 11, sessionId: 'first', hostUrl: 'http://127.0.0.1:1234', pane: '%0' });
  store.startExecution(run.id);
  store.recordAgentEvent(original.attempt.id, 1, { type: 'provider_request' });
  store.recordAgentEvent(original.attempt.id, 2, { type: 'provider_usage', status: 503, state: 'unavailable', reason: 'Unavailable' });
  store.recordAgentEvent(original.attempt.id, 3, { type: 'prompt_result', status: 'error', error: { provider: 'fixture', model: 'first', retryable: true, message: 'Provider unavailable.' } });
  assert.throws(() => store.replaceAttempt(original.assignment.id, { automatic: true, fallback: { model: next, eventSequence: 3 } }), /ownership/);
  store.beginPause(run.id); store.recordOwnership(original.attempt.id, true); store.finishPause(run.id);
  assert.throws(() => store.replaceAttempt(original.assignment.id, { automatic: true, fallback: { model: next, eventSequence: 2 } }), /recorded retryable/);
  assert.throws(() => store.replaceAttempt(original.assignment.id, { automatic: false, fallback: { model: next, eventSequence: 3 } }), /recorded retryable/);
  const replacement = store.replaceAttempt(original.assignment.id, { automatic: true, fallback: { model: next, eventSequence: 3 } });
  store.claimAttempt(replacement.id);
  store.recordAttemptIdentity(replacement.id, { hostPid: 12, ompPid: 13, sessionId: 'second', hostUrl: 'http://127.0.0.1:1235', pane: '%1' });
  store.recordAgentEvent(replacement.id, 1, { type: 'provider_request' });
  store.recordAgentEvent(replacement.id, 2, { type: 'provider_usage', status: 200, state: 'actual', usage: { input: 5, output: 2, total: 7, reasoning: 0, cacheRead: 0, cacheWrite: 0 } });
  store.recordAgentEvent(replacement.id, 3, { type: 'message_end', message: { role: 'assistant', provider: 'fixture', model: 'second', usage: { cost: { total: .25 } } } });
  store.close(); store = new Workbench(join(root, 'db'));
  const runtime = store.runtime(run.id); const history = readRunHistory(store, run.id);
  assert.equal(runtime.assignments[0].model.resolved.selector, 'fixture/first');
  assert.deepEqual(runtime.attempts.map(attempt => attemptModel(runtime.assignments[0], attempt).resolved.selector), ['fixture/first','fixture/second']);
  assert.equal(runtime.attempts[1].fallback?.fromAttemptId, original.attempt.id);
  assert.equal(runtime.attempts[1].fallback?.eventSequence, 3);
  assert.equal(runtime.attempts[1].input, original.attempt.input);
  assert.deepEqual(history.usage.rows.map(row => [row.model, row.state, row.costUsd]), [['fixture/first','unavailable',null],['fixture/second','actual',.25]]);
  assert.match(history.attempts[1].causes.join(' '), /Configured fallback from fixture\/first/);
  assert.equal(history.usage.total.tokens?.total, 7);
  assert.equal(attemptModel(runtime.assignments[0], {}).resolved.selector, 'fixture/first', 'Legacy identity remains its original admission.');
});
