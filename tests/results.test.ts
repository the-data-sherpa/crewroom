test('R5/LIM-04: per-attempt usage uses provider receipts, keeps unavailable responses distinct and never infers zero', async t => {
  const root = mkdtempSync(join(tmpdir(), 'crewroom-results-')); const store = new Workbench(join(root, 'db'));
  seedRepository(root);
  t.after(() => { store.close(); rmSync(root, { recursive: true, force: true }); });
  const repo = saveRepositoryFixture(store, { name: 'Fixture', path: root, targetBranch: 'main' });
  const task = store.createTask({ title: 'Usage provenance', description: '', repositoryId: repo.id });
  store.refine(task.id, { revision: 1, sourceRevision: 1, brief: 'Record known usage', criteria: ['Unknown cost is not zero'] }); const run = store.queue(task.id, { revision: 2 });
  const role = { ...defaultRoles[0], model: 'fixture/model', effort: 'low' as const };
  const model = resolveAssignment(role, [{ provider: 'fixture', id: 'model', api: 'openai-responses', inputs: ['text'], efforts: ['low'], tools: true }], {}, {});
  const { assignment, attempt } = store.admitAssignment(run.id, { name: 'Coordinator', role, model, coordinator: true, input: 'Coordinate' });
  store.claimAttempt(attempt.id); store.recordAttemptIdentity(attempt.id, { hostPid: 1, ompPid: 2, sessionId: 'session', hostUrl: 'http://127.0.0.1:5000', pane: '%0' });
  const actual = (input: number, output: number) => ({ type: 'provider_usage', status: 200, state: 'actual', usage: { input, output, cacheRead: 4, cacheWrite: 0, reasoning: 1, total: input + output } });
  const request = { type: 'provider_request', identity: { model: 'model' } };
  store.recordAgentEvent(attempt.id, 1, request); store.recordAgentEvent(attempt.id, 2, actual(10, 5));
  store.recordAgentEvent(attempt.id, 3, request); store.recordAgentEvent(attempt.id, 4, actual(20, 7));
  store.recordAgentEvent(attempt.id, 5, request); store.recordAgentEvent(attempt.id, 6, { type: 'provider_usage', status: 0, state: 'unavailable', reason: 'The provider response was interrupted before it completed.' });
  // The host stopped during this request, so its gateway never wrote a receipt.
  store.recordAgentEvent(attempt.id, 7, request);
  const first = { type: 'message_end', message: { role: 'assistant', timestamp: 100, provider: 'fixture', model: 'model', content: [{ type: 'text', text: 'First response' }], usage: { totalTokens: 999, cost: { total: 0.00007 } } } };
  store.recordAgentEvent(attempt.id, 8, first); store.recordAgentEvent(attempt.id, 9, first);
  store.recordAgentEvent(attempt.id, 10, { ...first, message: { ...first.message, timestamp: 300, usage: undefined } });
  store.recordOwnership(attempt.id, true); store.beginPause(run.id); store.finishPause(run.id);
  const replacement = store.replaceAttempt(assignment.id, { automatic: false }); store.claimAttempt(replacement.id);
  store.recordAttemptIdentity(replacement.id, { hostPid: 3, ompPid: 4, sessionId: 'session-2', hostUrl: 'http://127.0.0.1:5001', pane: '%1' });
  store.recordAgentEvent(replacement.id, 1, request); store.recordAgentEvent(replacement.id, 2, actual(1, 1));
  const work = new RepositoryWork(store, join(root, 'owned')); const results = new Results(store, work, new Evidence(store, work, join(root, 'artifacts')));
  const usage = (await results.read(run.id)).usage;
  const [original, second] = usage.rows;
  assert.equal(original.state, 'partial');
  assert.deepEqual(original.tokens, { input: 30, output: 12, cacheRead: 8, cacheWrite: 0, reasoning: 2, total: 42 }, 'Provider counts, not the runner message total.');
  assert.equal(original.actualResponses, 2); assert.equal(original.providerRequests, 4);
  assert.deepEqual(original.unavailableReasons, ['The provider response was interrupted before it completed.', '1 provider request(s) ended without a usage receipt.']);
  assert.equal(original.responses, 2, 'A replayed message is counted once.');
  assert.equal(original.costUsd, 0.00007); assert.equal(original.costResponses, 1);
  assert.equal(second.generation, 2); assert.equal(second.state, 'actual'); assert.equal(second.tokens?.total, 2);
  assert.equal(usage.billedUsd, null);
});

test('REP-02: Results and run history expose the prepared configuration after edit and retirement', async t => {
  const root = mkdtempSync(join(tmpdir(), 'crewroom-result-repository-'));
  const checkout = join(root, 'checkout'); seedRepository(checkout);
  const db = join(root, 'workflow.sqlite'); let store = new Workbench(db);
  t.after(() => { store.close(); rmSync(root, { recursive: true, force: true }); });
  const original = saveRepositoryFixture(store, { name: 'Before', path: checkout, targetBranch: 'main', branchPrefix: 'before/' });
  const task = store.createTask({ title: 'Historical work', description: '', repositoryId: original.id });
  const refined = store.refine(task.id, { revision: 1, sourceRevision: 1, brief: 'Preserve history', criteria: ['Show snapshot'] });
  const run = store.queue(task.id, { revision: refined.revision });
  const work = new RepositoryWork(store, join(root, 'owned'));
  await work.prepare(run.id, { mode: 'new' });
  store.cancelQueued(run.id, { requestId: randomUUID() });
  const edited = { name: 'After', path: checkout, targetBranch: 'main', branchPrefix: 'after/', checks: [], revision: 1, requestId: randomUUID() };
  const { revision, ...details } = edited;
  store.updateRepository(original.id, await validateRepository(details, path => store.isOwnedRepositoryWorktree(path)), edited);
  store.retireRepository(original.id, { revision: 2, requestId: randomUUID() });
  store.close(); store = new Workbench(db);
  const captured = store.snapshot().repositorySnapshots[run.id];
  const reopenedWork = new RepositoryWork(store, join(root, 'owned'));
  const results = new Results(store, reopenedWork, new Evidence(store, reopenedWork, join(root, 'artifacts')));
  const result = await results.read(run.id);
  assert.equal(store.snapshot().repositories.find(item => item.id === original.id)?.name, 'After');
  assert.equal(captured.name, 'Before'); assert.equal(captured.branchPrefix, 'before/');
  assert.deepEqual(result.repository, captured);
  assert.equal(store.getRun(run.id).status, 'cancelled');
});
